"""Aggregate parsed runs into summary tables and figures."""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path
import statistics
from typing import Iterable

try:
    import matplotlib.pyplot as plt
except ModuleNotFoundError:  # pragma: no cover - optional dependency in this workspace
    plt = None

from resource_metrics import collect_default_metrics, write_metrics_csv


def _load_rows(path: Path) -> list[dict[str, str]]:
    if not path.exists() or path.stat().st_size == 0:
        return []
    with path.open("r", newline="", encoding="ascii") as handle:
        return list(csv.DictReader(handle))


def _group_runs(rows: Iterable[dict[str, str]]) -> dict[tuple[str, str], list[dict[str, str]]]:
    grouped: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        grouped[(row["algorithm"], row["scenario"])].append(row)
    return grouped


def build_summary_rows(runs_csv: Path) -> list[dict[str, object]]:
    """Aggregate trial-level runs into algorithm/scenario summaries."""

    rows = _load_rows(runs_csv)
    summary_rows: list[dict[str, object]] = []

    for (algorithm, scenario), group in sorted(_group_runs(rows).items()):
        char_accuracy = [float(row["character_accuracy"]) for row in group]
        element_accuracy = [float(row["element_accuracy"]) for row in group]
        overrun_rate = [int(row["overrun_seen"]) for row in group]
        done_rate = [int(row["done_seen"]) for row in group]
        adaptation = [
            int(row["adaptation_elements"])
            for row in group
            if row["adaptation_elements"] not in ("", "None")
        ]

        summary_rows.append(
            {
                "algorithm": algorithm,
                "scenario": scenario,
                "run_count": len(group),
                "mean_character_accuracy": statistics.fmean(char_accuracy),
                "std_character_accuracy": statistics.pstdev(char_accuracy) if len(char_accuracy) > 1 else 0.0,
                "mean_element_accuracy": statistics.fmean(element_accuracy),
                "std_element_accuracy": statistics.pstdev(element_accuracy) if len(element_accuracy) > 1 else 0.0,
                "completion_rate": statistics.fmean(done_rate),
                "overrun_rate": statistics.fmean(overrun_rate),
                "mean_adaptation_elements": (
                    statistics.fmean(adaptation) if adaptation else ""
                ),
            }
        )

    return summary_rows


def write_summary_csv(summary_rows: list[dict[str, object]], output_path: Path) -> Path:
    """Write aggregated summary rows to CSV."""

    output_path.parent.mkdir(parents=True, exist_ok=True)
    if not summary_rows:
        output_path.write_text("", encoding="ascii")
        return output_path

    with output_path.open("w", newline="", encoding="ascii") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(summary_rows[0].keys()))
        writer.writeheader()
        writer.writerows(summary_rows)
    return output_path


def plot_accuracy(summary_rows: list[dict[str, object]], output_dir: Path) -> list[Path]:
    """Create one character-accuracy figure per scenario."""

    if plt is None:
        return []

    output_dir.mkdir(parents=True, exist_ok=True)
    grouped: dict[str, list[dict[str, object]]] = defaultdict(list)
    for row in summary_rows:
        grouped[str(row["scenario"])].append(row)

    figure_paths: list[Path] = []
    for scenario, rows in grouped.items():
        rows = sorted(rows, key=lambda row: str(row["algorithm"]))
        labels = [str(row["algorithm"]) for row in rows]
        values = [float(row["mean_character_accuracy"]) for row in rows]

        fig, ax = plt.subplots(figsize=(8, 4))
        ax.bar(labels, values)
        ax.set_ylim(0.0, 1.05)
        ax.set_ylabel("Character accuracy")
        ax.set_title(f"Scenario: {scenario}")
        ax.grid(axis="y", alpha=0.3)
        fig.tight_layout()

        path = output_dir / f"{scenario}_character_accuracy.png"
        fig.savefig(path, dpi=200)
        plt.close(fig)
        figure_paths.append(path)

    return figure_paths


def main() -> None:
    """Aggregate parsed runs, emit summary CSVs, and save figures."""

    import argparse

    parser = argparse.ArgumentParser(description="Analyze UART playback experiment results.")
    parser.add_argument(
        "--runs-csv",
        type=Path,
        default=Path("artifacts/parsed/runs.csv"),
        help="Run-level CSV generated by parse_logs.py",
    )
    parser.add_argument(
        "--summary-csv",
        type=Path,
        default=Path("artifacts/reports/summary.csv"),
        help="Algorithm/scenario summary CSV output path.",
    )
    parser.add_argument(
        "--figures-dir",
        type=Path,
        default=Path("artifacts/reports/figures"),
        help="Directory for generated PNG plots.",
    )
    parser.add_argument(
        "--resource-csv",
        type=Path,
        default=Path("artifacts/reports/resource_summary.csv"),
        help="Where to store parsed map-file resource metrics.",
    )
    args = parser.parse_args()

    summary_rows = build_summary_rows(args.runs_csv)
    summary_path = write_summary_csv(summary_rows, args.summary_csv)
    figure_paths = plot_accuracy(summary_rows, args.figures_dir) if summary_rows else []
    resource_path = write_metrics_csv(collect_default_metrics(), args.resource_csv)

    print(f"Summary CSV: {summary_path}")
    for figure_path in figure_paths:
        print(f"Figure: {figure_path}")
    print(f"Resource CSV: {resource_path}")


if __name__ == "__main__":
    main()
